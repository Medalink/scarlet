#!/usr/bin/env node
// feats-gen.mjs <feats.json> [--out FILE]: writes addon/Scarlet/FeatCatalog.lua from the feat catalog of
// CONTRACTS.md ("The catalog in each repo"). Only the fields the addon reads are written, keys are sorted and
// feats keep the catalog's order, so a second run changes nothing.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const at = args.indexOf("--out");
const out = resolve(at < 0 ? join(here, "../addon/Scarlet/FeatCatalog.lua") : args.splice(at, 2)[1]);
const input = args[0];
if (!input) {
  console.error("usage: node scripts/feats-gen.mjs <feats.json> [--out FILE]");
  process.exit(2);
}

const catalog = JSON.parse(readFileSync(input, "utf8"));
const FIELDS = ["key", "name", "family", "collection", "class", "tree", "role", "glyph", "icon", "one", "many", "unit", "economy", "spells", "thresholds", "live"];
const ICON_GLYPH = { spell: "spell", tree: "talents" };

const derive = (f) => {
  if (f.scope === "tree") return { family: "class", collection: `${f.class}, ${f.tree}` };
  if (f.scope === "class") return { family: "class", collection: f.class };
  if (f.scope === "role") return { family: "role" };
  return {};
};

const slim = (f) => {
  const d = derive(f);
  const o = { ...f };
  if (f.scope !== "general" && o.family !== d.family) throw new Error(`${f.key}: family is not derivable`);
  if (d.collection !== undefined && o.collection !== d.collection) throw new Error(`${f.key}: collection is not derivable`);
  if (!["general", "class", "tree", "role"].includes(f.scope)) throw new Error(`${f.key}: unknown scope`);
  if (f.scope !== "general") delete o.family;
  if (d.collection !== undefined) delete o.collection;
  if (f.icon && f.glyph === ICON_GLYPH[f.icon]) delete o.glyph;
  if (f.live) o.live = { ...f.live, note: undefined };
  return o;
};
const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;

const str = (s) =>
  '"' +
  [...Buffer.from(String(s), "utf8")]
    .map((b) => {
      if (b === 0x5c) return "\\\\";
      if (b === 0x22) return '\\"';
      if (b === 0x0a) return "\\n";
      if (b < 0x20 || b > 0x7e) return "\\" + String(b).padStart(3, "0");
      return String.fromCharCode(b);
    })
    .join("") +
  '"';

const value = (v) => {
  if (Array.isArray(v)) return "{" + v.map(value).join(",") + "}";
  if (v && typeof v === "object") return table(v, Object.keys(v).sort());
  if (typeof v === "string") return str(v);
  return String(v);
};
const table = (o, keys) =>
  "{" + keys.filter((k) => o[k] !== undefined).map((k) => `${IDENT.test(k) ? k : `[${str(k)}]`}=${value(o[k])}`).join(",") + "}";

const lines = [
  "-- @generated by scripts/feats-gen.mjs from the feat catalog. Do not edit by hand.",
  "local _, ns = ...",
  "",
  `ns.FEAT_CATALOG = ${catalog.version}`,
  `ns.FEAT_TIER_NAMES = ${value(catalog.tiers)}`,
  `ns.FEAT_FAMILIES = ${value(catalog.families)}`,
  `ns.FEAT_ROLE_CLASSES = ${value(catalog.role_classes)}`,
  `ns.FEAT_SPEC_ROLES = ${value(catalog.spec_roles)}`,
  "ns.FEATS = {",
  ...catalog.feats.map((f) => table(slim(f), FIELDS) + ","),
  "}",
  "",
  "local ICON_GLYPH = { spell = \"spell\", tree = \"talents\" }",
  "for _, f in ipairs(ns.FEATS) do",
  "    if f.tree then",
  "        f.scope, f.family, f.collection = \"tree\", \"class\", f.class .. \", \" .. f.tree",
  "    elseif f.class then",
  "        f.scope, f.family, f.collection = \"class\", \"class\", f.class",
  "    elseif f.role then",
  "        f.scope, f.family = \"role\", \"role\"",
  "    else",
  "        f.scope = \"general\"",
  "    end",
  "    if f.icon and not f.glyph then f.glyph = ICON_GLYPH[f.icon] end",
  "end",
  "",
];
const text = lines.join("\n");
writeFileSync(out, text);
console.log(`${out}: ${catalog.feats.length} feats, catalog ${catalog.version}, ${Buffer.byteLength(text)} bytes`);
